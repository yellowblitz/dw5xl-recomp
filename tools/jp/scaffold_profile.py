#!/usr/bin/env python3
"""Create a *starter* PS2Recomp main-ELF profile from a Japanese disc report.

This is deliberately not a working recompilation configuration: Ghidra must
establish Japanese function boundaries, stubs, entries and address patches.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


def build_config(manifest: dict) -> str:
    boot = manifest.get("boot_executable", "")
    if not re.fullmatch(r"(?:SLPM|SLPS)_[0-9]{3}\.[0-9]{2}", boot):
        raise ValueError("Expected Japanese SLPM/SLPS boot executable in manifest")
    return f'''# Japanese PS2 executable: {boot}
# DEVELOPMENT SCAFFOLD ONLY - not ready to compile or play.
# Re-run Ghidra analysis for the actual Japanese ELF; never copy PAL addresses.
[general]
input = "game/dw5xl_jp/{boot}"
ghidra_output = "recomp/dw5xl_jp/ghidra_functions.code.csv"
output = "recomp/dw5xl_jp/output/"
single_file_output = false
output_file_batch_size = 64
patch_syscalls = false
patch_cop0 = true
patch_cache = true
# TODO: Populate Japanese function map and verify handlers/addresses individually.
stubs = []
entry_points = []
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("manifest", type=Path, help="JSON generated by inspect_disc.py")
    parser.add_argument("--output", type=Path, default=Path("recomp/dw5xl_jp/main.toml"))
    args = parser.parse_args()
    try:
        manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
        content = build_config(manifest)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        # Do not overwrite developer-maintained maps/configs by accident.
        with args.output.open("x", encoding="utf-8") as handle:
            handle.write(content)
        print(f"Created starter profile {args.output}. Ghidra analysis is still required.")
        return 0
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        parser.error(str(exc))


if __name__ == "__main__":
    raise SystemExit(main())
